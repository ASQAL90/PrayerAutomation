"""Generate the NSIS payload include from technically reviewed receipts.

The generated include contains only explicit File entries, the per-architecture
install manifests and the uninstall delete list. No wildcard and no product
build. The receipts are re-hashed here before anything is written; the build
wrapper runs this script immediately before makensis so a stale receipt can
never be packaged silently. Stdlib only.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path, PurePosixPath

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_accepted_payload import UI_NAME, validated_payload  # noqa: E402

HEADER = [
    "; Generated by generate_nsis_payload.py. Do not edit by hand.",
    "; Every path below comes from the reviewed x64/x86 receipts and was",
    "; re-hashed before this file was written. Re-run the generator instead.",
    "; Shared files are installed once; architecture files are gated at runtime.",
]
PLACEHOLDER_MARKER = "; PLACEHOLDER"


def nsis_text(value: str) -> str:
    """Quote a path or line for an NSIS string literal."""
    return value.replace("$", "$$").replace('"', '$\\"')


def parent_of(rel: str) -> str:
    parent = str(PurePosixPath(rel).parent)
    return "" if parent == "." else parent


def render_file_group(lines: list[str], source: str, files: list[str]) -> None:
    by_dir: dict[str, list[str]] = {}
    for rel in files:
        by_dir.setdefault(parent_of(rel), []).append(rel)
    for directory in sorted(by_dir):
        target = "$INSTDIR" if not directory else f"$INSTDIR\\{nsis_text(directory)}"
        lines.append(f'  SetOutPath "{target}"')
        for rel in sorted(by_dir[directory]):
            lines.append(f'  File "{source}/{nsis_text(rel)}"')


def render_manifest_macro(lines: list[str], name: str, files: list[str]) -> None:
    lines.append(f"!macro {name}")
    lines.append('  FileOpen $0 "$LOCALAPPDATA\\PrayerAutomation\\install-manifest.txt" w')
    for rel in sorted(files):
        lines.append(f'  FileWrite $0 "{nsis_text(rel)}$\\r$\\n"')
    lines.append("  FileClose $0")
    lines.append("!macroend")


def render_delete_macro(lines: list[str], files: list[str]) -> None:
    directories = sorted({parent_of(rel) for rel in files if parent_of(rel)},
                         key=lambda value: (-value.count("/"), value))
    lines.append("!macro NSIS_DELETE_PAYLOAD")
    for rel in sorted(files):
        lines.append(f'  Delete "$INSTDIR\\{nsis_text(rel)}"')
    for directory in directories:
        lines.append(f'  RMDir "$INSTDIR\\{nsis_text(directory)}"')
    lines.append("!macroend")


def render(payload_x64: dict[str, str], payload_x86: dict[str, str]) -> str:
    shared = {rel: digest for rel, digest in payload_x64.items()
              if payload_x86.get(rel) == digest}
    x64_only = {rel: digest for rel, digest in payload_x64.items() if rel not in shared}
    x86_only = {rel: digest for rel, digest in payload_x86.items() if rel not in shared}
    all_files = sorted(set(payload_x64) | set(payload_x86))

    lines = list(HEADER)
    lines.append(f"; x64 files={len(payload_x64)} x86 files={len(payload_x86)} "
                 f"unique={len(all_files)} shared={len(shared)}")
    lines.append(f"; ui_sha256_x64={payload_x64[UI_NAME]}")
    lines.append(f"; ui_sha256_x86={payload_x86[UI_NAME]}")
    lines.append("")

    lines.append("!define NSIS_PAYLOAD_COUNT_X64 " + str(len(payload_x64)))
    lines.append("!define NSIS_PAYLOAD_COUNT_X86 " + str(len(payload_x86)))
    lines.append("!define NSIS_PAYLOAD_COUNT_UNIQUE " + str(len(all_files)))
    lines.append("!define NSIS_PAYLOAD_COUNT_SHARED " + str(len(shared)))
    lines.append("")

    lines.append('Section "Berkas aplikasi (bersama)" SEC_PAYLOAD_SHARED')
    render_file_group(lines, "${PAYLOAD_X64}", sorted(shared))
    lines.append("SectionEnd")
    lines.append("")

    lines.append('Section "Berkas aplikasi 64-bit" SEC_PAYLOAD_X64')
    render_file_group(lines, "${PAYLOAD_X64}", sorted(x64_only))
    lines.append("SectionEnd")
    lines.append("")

    lines.append('Section "Berkas aplikasi 32-bit" SEC_PAYLOAD_X86')
    render_file_group(lines, "${PAYLOAD_X86}", sorted(x86_only))
    lines.append("SectionEnd")
    lines.append("")

    render_manifest_macro(lines, "NSIS_WRITE_MANIFEST_X64", sorted(payload_x64))
    lines.append("")
    render_manifest_macro(lines, "NSIS_WRITE_MANIFEST_X86", sorted(payload_x86))
    lines.append("")
    render_delete_macro(lines, all_files)
    lines.append("")
    return "\n".join(lines)


def write_output(output: Path, content: str, force: bool) -> None:
    if output.exists():
        existing = output.read_text(encoding="utf-8")
        if existing != content and PLACEHOLDER_MARKER not in existing and not force:
            raise ValueError("Existing NSIS payload include differs; review the new "
                             "payload deliberately and rerun with --force")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8", newline="\n")


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate the NSIS payload include")
    parser.add_argument("--receipt-x64", type=Path, required=True)
    parser.add_argument("--source-x64", type=Path, required=True)
    parser.add_argument("--receipt-x86", type=Path, required=True)
    parser.add_argument("--source-x86", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--force", action="store_true",
                        help="Replace an existing include after reviewing the new payload")
    args = parser.parse_args()

    payload_x64 = validated_payload(args.receipt_x64, args.source_x64)
    payload_x86 = validated_payload(args.receipt_x86, args.source_x86)
    content = render(payload_x64, payload_x86)
    write_output(args.output, content, args.force)
    print(json.dumps({
        "status": "PASS",
        "mode": "nsis-dual",
        "files_x64": len(payload_x64),
        "files_x86": len(payload_x86),
        "files_unique": len(set(payload_x64) | set(payload_x86)),
        "shared_files": sum(1 for rel in payload_x64 if payload_x86.get(rel) == payload_x64[rel]),
        "ui_dll_sha256_x64": payload_x64[UI_NAME],
        "ui_dll_sha256_x86": payload_x86[UI_NAME],
        "output": str(args.output),
    }, indent=2))


if __name__ == "__main__":
    try:
        main()
    except ValueError as error:
        print(f"ERROR: {error}", file=sys.stderr)
        raise SystemExit(1)
